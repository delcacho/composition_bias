"""Synthetic checks of research/etf_factor_benchmark.py (the return-based factor benchmark).

World: N names driven by K_true factors plus specific noise over T days. Funds are portfolios of the names:
  A  fixed weights, observed over the whole window;
  B  fixed weights, observed only over the last SHORT days (a young fund);
  C  weights that rotate at day T - SHORT (a young-looking record generated by a book it no longer holds).
Truth: the correlation implied by today's weights through the true covariance.
Checks: (1) identity on long records: rho^F(A, B_long) matches the holdings correlation within tolerance;
(2) the young-fund case: rho^F(A, B) is closer to the truth than the short-record sample correlation, on average
over seeds; (3) rotation: rho^F(A, C) misses the truth by more than rho^F(A, B) does. Both directions of (2)
and (3) are asserted (fires / does not fire)."""
import os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import etf_factor_benchmark as fb  # noqa: E402
import return_availability as ra  # noqa: E402


def world(seed, N=150, T=378, K_true=3, SHORT=80):
    rng = np.random.default_rng(seed)
    Lm = rng.standard_normal((N, K_true)) * np.array([1.0, 0.6, 0.4])
    Sf = np.diag([1.0, 0.5, 0.3]) * 1e-4
    spec = 1e-4 * rng.uniform(0.5, 2.0, N)
    Sig_true = Lm @ Sf @ Lm.T + np.diag(spec)
    f = rng.multivariate_normal(np.zeros(K_true), Sf, T)
    X = f @ Lm.T + rng.standard_normal((T, N)) * np.sqrt(spec)
    A = np.ones((T, N), bool)
    wA = np.zeros(N); wA[:40] = 1 / 40
    wB = np.zeros(N); wB[40:80] = 1 / 40
    wC_old = np.zeros(N); wC_old[80:120] = 1 / 40          # the book C held before it rotated
    wC_new = np.zeros(N); wC_new[:20] = 1 / 40; wC_new[120:140] = 1 / 40
    rA = X @ wA; rB = X @ wB
    rC = np.where(np.arange(T) < T - SHORT, X @ wC_old, X @ wC_new)
    rw = np.column_stack([rA, rB, rB, rC]); hw = np.ones((T, 4), bool)
    hw[:T - SHORT, 2] = False                                  # column 2: B observed only over the last SHORT days
    rw = np.where(hw, rw, 0.0)
    wts = np.full(T, 1.0 / T)
    return X, A, Sig_true, rw, hw, wts, (wA, wB, wC_new), SHORT


def true_corr(Sig, w1, w2):
    return w1 @ Sig @ w2 / np.sqrt((w1 @ Sig @ w1) * (w2 @ Sig @ w2))


def run(seed):
    X, A, Sig_true, rw, hw, wts, (wA, wB, wC), SHORT = world(seed)
    Sig = ra.masked_cov(X, A, wts)
    priced = np.ones(X.shape[1], bool)
    rho = fb.factor_correlations(X, A, Sig, priced, rw, hw, wts, Ks=(5,))[5]
    t_AB = true_corr(Sig_true, wA, wB); t_AC = true_corr(Sig_true, wA, wC)
    hold_AB = true_corr(Sig, wA, wB)                            # holdings correlation through the sample covariance
    short = rw[-SHORT:, [0, 2]]; sc = short.T @ short; samp_AB = sc[0, 1] / np.sqrt(sc[0, 0] * sc[1, 1])
    return dict(long_err=abs(rho[0, 1] - t_AB), hold_err=abs(hold_AB - t_AB), factor_err=abs(rho[0, 2] - t_AB),
                sample_err=abs(samp_AB - t_AB), rot_err=abs(rho[0, 3] - t_AC), rho=rho)


def test_long_records_recover_the_true_correlation():
    res = [run(s) for s in range(12)]
    assert all(np.isfinite(r["rho"]).all() for r in res)
    le = np.mean([r["long_err"] for r in res]); he = np.mean([r["hold_err"] for r in res])
    assert le < 0.06, le                                        # the factor route reaches the truth on a long record
    assert le < he + 0.02, (le, he)                             # and no worse than the holdings route through the sample covariance


def test_young_fund_factor_model_beats_short_sample_correlation():
    res = [run(s) for s in range(12)]
    fe = np.mean([r["factor_err"] for r in res]); se = np.mean([r["sample_err"] for r in res])
    assert fe < se, (fe, se)                                   # fires: borrows the window through the factors
    assert fe < 0.10, fe


def test_rotating_fund_is_mispriced_by_its_own_returns():
    res = [run(s) for s in range(12)]
    fe = np.mean([r["factor_err"] for r in res]); re = np.mean([r["rot_err"] for r in res])
    assert re > fe + 0.05, (re, fe)                            # does not fire on rotation: the loadings are the old book's


def test_named_proxies_that_are_the_true_factors_recover_the_truth():
    """proxy_correlations with the true factor portfolios as proxies: a young fund's correlation is recovered."""
    X, A, Sig_true, rw, hw, wts, (wA, wB, wC), SHORT = world(5, SHORT=150)   # 13 proxies need a 130-day record
    rng = np.random.default_rng(11)
    Wp = rng.dirichlet(np.ones(X.shape[1]), 13)                         # 13 random long-only proxy portfolios
    Xp = X @ Wp.T; Ap = np.ones(Xp.shape, bool)
    rho = fb.proxy_correlations(Xp, Ap, rw, hw, wts, sets=(13,))[13]
    t_AB = true_corr(Sig_true, wA, wB)
    assert np.isfinite(rho[0, 2]) and abs(rho[0, 2] - t_AB) < 0.10, (rho[0, 2], t_AB)
    short = rw[-SHORT:, [0, 2]]; sc = short.T @ short; samp = sc[0, 1] / np.sqrt(sc[0, 0] * sc[1, 1])
    assert abs(rho[0, 2] - t_AB) <= abs(samp - t_AB) + 0.02


def test_short_record_is_undefined_below_the_minimum():
    X, A, Sig_true, rw, hw, wts, _, SHORT = world(3)
    hw2 = hw.copy(); hw2[:-30, 2] = False; rw2 = np.where(hw2, rw, 0.0)    # 30 days: below MIN_OBS
    Sig = ra.masked_cov(X, A, wts)
    rho = fb.factor_correlations(X, A, Sig, np.ones(X.shape[1], bool), rw2, hw2, wts, Ks=(5,))[5]
    assert np.isnan(rho[0, 2]) and np.isnan(rho[2, 0]) and np.isfinite(rho[0, 1])
